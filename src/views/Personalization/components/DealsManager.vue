<script setup lang="ts">
import { ref, onMounted, computed, watch, onUnmounted, nextTick } from 'vue';
import PersonalizationService from '@/services/PersonalizationService';
import { productService } from '@/services/api';
import api from '@/services/api';
import { useUIStore } from '@/stores/ui';

const uiStore = useUIStore();
const loading = ref(false);
const saving = ref(false);
const isUploading = ref(false);
const showModal = ref(false);
const editingIndex = ref<number | null>(null);

// Watch showModal to lock/unlock body scroll
watch(showModal, (newVal) => {
  if (newVal) document.body.style.overflow = 'hidden';
  else document.body.style.overflow = '';
});

onUnmounted(() => { document.body.style.overflow = ''; });

const config = ref({
  section: 'deals_to_discover',
  isActive: true,
  content: {
    mode: 'automatic', // 'automatic' | 'manual'
    items: [] as any[], // Display items (Fetched from backend)
    manualItems: [] as any[] // Manual items specific storage
  }
});

// Which items to display in the list?
// We use content.items because it contains the merged result (Auto + Manual) from backend.
const displayItems = computed(() => {
    return config.value.content.items || [];
});

// Helper to determine if an item is auto-generated (not editable)
const isAutoGenerated = (item: any) => {
    // We assume items starting with 'auto-' id are automatic.
    // Or we can check if they exist in manualItems list.
    // Simpler: Check if it has an id starting with 'auto-'.
    return item.id && String(item.id).startsWith('auto-');
};

// Which items are we actually editing?
const editableItems = computed(() => {
    if (config.value.content.mode === 'automatic') {
        return config.value.content.manualItems || [];
    }
    return config.value.content.items || [];
});

// Modal Form State
const itemForm = ref<any>({
  type: '',
  title: '',
  link: '',
  linkText: 'Voir plus',
  items: [{}, {}, {}, {}], 
  subtitle: '',
  promoText: '',
  promoTextSize: 'text-2xl',
  promoTextWeight: 'font-bold',
  promoTextColor: '#ffffff',
  image: '',
  promoStyle: 'image',
  backgroundColor: '#2563eb'
});

// Product Picker State
const showProductPicker = ref(false);
const currentSlotIndex = ref(0);
const searchQuery = ref('');
const searchResults = ref<any[]>([]);
const isSearching = ref(false);
let searchTimeout: any = null;
const searchInput = ref<HTMLInputElement | null>(null);

const loadConfig = async () => {
  loading.value = true;
  try {
    const response = await PersonalizationService.getSectionConfig('deals_to_discover');
    if (response.data) {
      config.value = { 
        ...response.data, 
        content: { 
            mode: 'automatic', 
            items: [], 
            manualItems: [],
            ...response.data.content 
        } 
      };
    }
  } catch (error) {
    console.error('Failed to load deals config', error);
  } finally {
    loading.value = false;
  }
};

const saveConfig = async () => {
  saving.value = true;
  try {
    const cleanConfig = JSON.parse(JSON.stringify(config.value));
    
    // Logic to sanitize data before save
    if (cleanConfig.content.mode === 'automatic') {
        // In automatic mode, 'items' is the computed list from backend. WE SHOULD NOT SAVE IT back to DB.
        // We only save 'manualItems'.
        cleanConfig.content.items = []; // Clear computed items to avoid DB bloat/duplication
    } else {
        // In manual mode, 'items' IS the source of truth.
        // We might want to clear 'manualItems' or keep them?
        // Let's keep manualItems in sync or clear them?
        // If we switch from Auto to Manual, users might expect 'items' to be empty or start with manual items?
        // Current implementation uses 'items' for manual mode display/edit.
        // So we just ensure 'items' is populated.
        cleanConfig.content.manualItems = []; // Clean up manual specific container
    }

    await PersonalizationService.updateSectionConfig('deals_to_discover', cleanConfig);
    await loadConfig(); // Reload to get fresh computed data (especially for auto mode)
    await api.post('/personalization/sections/deals', config.value);
    uiStore.addToast('Configuration enregistrée avec succès', 'success');
  } catch (error: any) {
    console.error('Failed to save config', error);
    uiStore.addToast('Erreur lors de l\'enregistrement : ' + (error.response?.data?.error || error.message), 'error');
  } finally {
    saving.value = false;
  }
};

