const moveItem = (displayIndex: number, dir: number) => {
     // Moving items support.
     // In Auto mode, moving auto items is disabled. Moving manual items within manual section?
     if (config.value.content.mode === 'automatic') {
          const autoCount = displayItems.value.length - (config.value.content.manualItems?.length || 0);
          const sourceIndex = displayIndex - autoCount;
          const newSourceIndex = sourceIndex + dir;
          
          if (sourceIndex >= 0 && newSourceIndex >= 0 && newSourceIndex < config.value.content.manualItems.length) {
                // Swap in manualItems
                const item = config.value.content.manualItems.splice(sourceIndex, 1)[0];
                config.value.content.manualItems.splice(newSourceIndex, 0, item);
                
                // Swap in displayItems (for view)
                const dItem = config.value.content.items.splice(displayIndex, 1)[0];
                config.value.content.items.splice(displayIndex + dir, 0, dItem);
          }
     } else {
         // Manual mode: standard swap
         const newIndex = displayIndex + dir;
         if (newIndex >= 0 && newIndex < config.value.content.items.length) {
            const item = config.value.content.items.splice(displayIndex, 1)[0];
            config.value.content.items.splice(newIndex, 0, item);
         }
     }
};


