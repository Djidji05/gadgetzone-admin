const editDisplayItem = (displayIndex: number) => {
    // Only manual items are editable.
    // We need to find this item in our source array.
    // If Mode == Manual, source is config.content.items.
    // If Mode == Auto, source is config.content.manualItems.
    
    // In Manual mode, displayIndex IS the source index.
    // In Auto mode, displayIndex is Offset + Source Index?
    // Backend logic: computedConfig.content.items = [...autoCards, ...manualItems];
    // So Manual items are at the end.
    
    if (config.value.content.mode === 'automatic') {
        // Calculate offset
        const autoCount = displayItems.value.length - (config.value.content.manualItems?.length || 0);
        const sourceIndex = displayIndex - autoCount;
        
        if (sourceIndex >= 0) {
            // It is a manual item
            editingIndex.value = sourceIndex; // We use Source Index for editing state!
            const item = config.value.content.manualItems[sourceIndex];
            itemForm.value = JSON.parse(JSON.stringify(item));
             if (itemForm.value.type === 'grid' && (!itemForm.value.items || itemForm.value.items.length !== 4)) {
                itemForm.value.items = itemForm.value.items || [];
                while(itemForm.value.items.length < 4) itemForm.value.items.push({});
            }
            showModal.value = true;
        } else {
            console.error('Cannot edit auto item');
        }
    } else {
        // Manual mode
        editingIndex.value = displayIndex;
        openModal(displayIndex);
    }
};

